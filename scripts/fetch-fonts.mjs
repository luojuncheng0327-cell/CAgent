// Downloads the SIL OFL fonts the interface uses from Google Fonts' official CSS API into
// src/ui/fonts/: the woff2 files (unmodified), each family's licence text from the google/fonts
// repository, a stylesheet pointing at the local copies and a provenance manifest.
// Behind a proxy, run with NODE_USE_ENV_PROXY=1 so fetch honours HTTPS_PROXY.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import * as prettier from 'prettier';

const OUT = 'src/ui/fonts';
const FILES = path.join(OUT, 'files');
const LICENSES = path.join(OUT, 'licenses');
// A current desktop browser agent makes the API answer with woff2 split by unicode-range.
const AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const FAMILIES = [
  { name: 'Inter', slug: 'inter', axes: 'wght@400..700', licence: 'ofl/inter/OFL.txt' },
  {
    name: 'EB Garamond',
    slug: 'eb-garamond',
    axes: 'ital,wght@0,400..700;1,400..700',
    licence: 'ofl/ebgaramond/OFL.txt',
  },
  {
    name: 'PT Serif',
    slug: 'pt-serif',
    axes: 'ital,wght@0,400;0,700;1,400;1,700',
    licence: 'ofl/ptserif/OFL.txt',
  },
  {
    name: 'Noto Serif SC',
    slug: 'noto-serif-sc',
    axes: 'wght@400..700',
    licence: 'ofl/notoserifsc/OFL.txt',
  },
  {
    name: 'JetBrains Mono',
    slug: 'jetbrains-mono',
    axes: 'wght@400..700',
    licence: 'ofl/jetbrainsmono/OFL.txt',
  },
];
// Scripts the interface does not need; system fonts cover them.
const UNUSED = new Set(['cyrillic', 'cyrillic-ext', 'greek', 'greek-ext', 'vietnamese']);

async function download(url, binary) {
  const response = await fetch(url, { headers: { 'user-agent': AGENT } });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return binary ? Buffer.from(await response.arrayBuffer()) : response.text();
}

// Script subsets carry a comment such as `/* latin */`; CJK slices come without one and are
// named after the slice number at the end of their file URL.
function faces(css) {
  return [...css.matchAll(/(?:\/\*\s*([^*]+?)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g)].map(
    ([, comment, body]) => {
      const props = Object.fromEntries(
        [...body.matchAll(/([\w-]+)\s*:\s*([^;]+);/g)].map(([, key, value]) => [key, value.trim()]),
      );
      const url = props.src.match(/url\((.+?)\)/)[1];
      const slice = url.match(/\.(\d+)\.woff2$/);
      const label = comment
        ? comment.replace(/[[\]]/g, '')
        : slice
          ? 'part' + slice[1].padStart(3, '0')
          : crypto.createHash('sha256').update(url).digest('hex').slice(0, 8);
      return { label, props, url };
    },
  );
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(FILES, { recursive: true });
fs.mkdirSync(LICENSES, { recursive: true });
const manifest = { generatedAt: new Date().toISOString(), families: [] };
const rules = [];
for (const family of FAMILIES) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=${family.name.replaceAll(' ', '+')}:${family.axes}&display=swap`;
  const licenceUrl = `https://raw.githubusercontent.com/google/fonts/main/${family.licence}`;
  const licenceFile = `${family.slug}-OFL.txt`;
  fs.writeFileSync(path.join(LICENSES, licenceFile), await download(licenceUrl, false));
  const record = {
    name: family.name,
    cssUrl,
    licence: { url: licenceUrl, file: licenceFile },
    files: [],
  };
  for (const face of faces(await download(cssUrl, false))) {
    if (UNUSED.has(face.label)) continue;
    const italic = face.props['font-style'] === 'italic';
    const weight = face.props['font-weight'];
    const file = [family.slug, italic && 'italic', !weight.includes(' ') && weight, face.label]
      .filter(Boolean)
      .join('-')
      .concat('.woff2');
    const bytes = await download(face.url, true);
    fs.writeFileSync(path.join(FILES, file), bytes);
    record.files.push({
      file,
      url: face.url,
      bytes: bytes.length,
      sha256: crypto.createHash('sha256').update(bytes).digest('hex'),
    });
    rules.push(
      [
        '@font-face {',
        `  font-family: '${family.name}';`,
        `  src: url('./files/${file}') format('woff2');`,
        `  font-weight: ${weight};`,
        `  font-style: ${face.props['font-style']};`,
        `  unicode-range: ${face.props['unicode-range']};`,
        '  font-display: swap;',
        '}',
      ].join('\n'),
    );
  }
  manifest.families.push(record);
  console.log(`${family.name}: ${record.files.length} files`);
}
const stylesheet = path.join(OUT, 'fonts.css');
fs.writeFileSync(
  stylesheet,
  await prettier.format(
    '/* Generated by scripts/fetch-fonts.mjs from Google Fonts; SIL Open Font License 1.1, see licenses/. */\n' +
      rules.join('\n'),
    { ...(await prettier.resolveConfig(stylesheet)), filepath: stylesheet },
  ),
);
fs.writeFileSync(path.join(OUT, 'sources.json'), JSON.stringify(manifest, null, 2) + '\n');
const total = manifest.families.flatMap((f) => f.files).reduce((n, f) => n + f.bytes, 0);
console.log(JSON.stringify({ files: rules.length, megabytes: +(total / 1048576).toFixed(2) }));
